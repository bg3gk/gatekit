    /// <summary>What a run found and would write.</summary>
    public sealed class Result
    {
        public int Layouts, Emitted;
        /// <summary>file: problem, for every layout that does not hold together.</summary>
        public List<string> Invalid { get; } = [];
        /// <summary>How many of those are in the build - which stops the run.</summary>
        public int InvalidInBuild;
        /// <summary>Layouts left out because Script Extender declares the type itself now.</summary>
        public List<string> DeclaredUpstream { get; } = [];
        public string? HeaderText, EnumerationText;
    }

    /// <summary>Validates every layout and, if those in the build hold together, renders the header
    /// and the enumeration. Nothing is written here.</summary>
    public Result Run(IEnumerable<LayoutFile> files, bool checkOnly = false)
    {
        var result = new Result();
        var inBuild = new List<JsonObject>();
        foreach (var file in files.Where(f => !f.IsSystem))
        {
            result.Layouts++;
            try
            {
                Validate(file.Json);
            }
            catch (LayoutError problem)
            {
                // an unfinished hypothesis may be invalid; a layout in the build may not
                if (file.InBuild) result.InvalidInBuild++;
                result.Invalid.Add($"{file.Name}: {problem.Message}");
            }
            if (file.InBuild && !LayoutFile.Truthy(file.Json["hold"]))
                inBuild.Add(file.Json);
        }
        var upstream = DeclaredUpstream();
        result.DeclaredUpstream.AddRange(inBuild.Select(l => Str(l, "component")).Where(upstream.Contains).Order(StringComparer.Ordinal));
        inBuild = inBuild.Where(l => !upstream.Contains(Str(l, "component"))).ToList();
        result.Emitted = inBuild.Count;
        if (result.InvalidInBuild == 0 && !checkOnly)
        {
            result.HeaderText = Render(inBuild);
            result.EnumerationText = RenderEnumeration(inBuild);
        }
        return result;
    }

    /// <summary>Opens the symbol database if there is one; the declarations of most layouts need none.</summary>
    public static SqliteConnection? OpenSymbols(string? path)
    {
        path ??= SymbolPaths.SymbolsDb;
        return GateKit.Home.HomeDatabase.Usable(path) ? Sql.OpenReadOnly(path) : null;
    }
