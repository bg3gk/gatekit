    void ValidateFields(string owner, List<JsonNode> fields, int size, Dictionary<string, (int, int)> local)
    {
        int position = 0, widest = 1;
        foreach (var field in fields)
        {
            string name = Str(field, "name");
            int offset = Int(field, "offset");
            var (fieldSize, align) = TypeSize(Str(field, "type"), local);
            widest = Math.Max(widest, align);
            if (offset < position)
                throw new LayoutError($"{owner}.{name}: overlaps the field before it");
            if (offset % align != 0)
                throw new LayoutError($"{owner}.{name}: offset {offset} is not aligned to {align}");
            int natural = Up(position, align);
            if (!IsPadding(field) && offset != natural)
                throw new LayoutError($"{owner}.{name}: C++ would place it at {natural}, the layout says {offset}; add the unknown field in between");
            string? source = LayoutFile.Text(field["source"]);
            if ((source is null || !Sources.ContainsKey(source)) && !IsPadding(field))
                throw new LayoutError($"{owner}.{name}: source must be one of {string.Join(", ", Sources.Keys.Order(StringComparer.Ordinal))}");
            if (source == "inferred" && !LayoutFile.Truthy(field["evidence"]))
                throw new LayoutError($"{owner}.{name}: an inferred name needs its evidence");
            position = offset + fieldSize;
        }
        int total = Up(position, widest);
        if (total != size)
            throw new LayoutError($"{owner}: fields end at {position} (struct size {total}), expected {size}");
    }

    /// <summary>Fields in order, no overlap, alignment respected, the size covered exactly - for the
    /// component and for every nested struct.</summary>
    public void Validate(JsonObject layout)
    {
        string name = Str(layout, "component");
        if (LayoutFile.Truthy(layout["tag"]))
        {
            if (LayoutFile.Truthy(layout["fields"]))
                throw new LayoutError($"{name}: a tag has no fields");
            return;
        }
        var local = LocalTypes(layout);
        foreach (var nested in List(layout, "structs"))
            ValidateFields($"{name}/{Str(nested, "name")}", List(nested, "fields"), Int(nested, "size"), local);
        if (layout["fields"] is not JsonArray)
            throw new LayoutError("\"fields\" is missing");
        ValidateFields(name, List(layout, "fields"), Int(layout, "size"), local);
    }

