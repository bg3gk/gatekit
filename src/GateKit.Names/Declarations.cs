    static IEnumerable<string> Comment(JsonNode field)
    {
        string text = Sources[Str(field, "source")];
        if (LayoutFile.Text(field["evidence"]) is { Length: > 0 } evidence)
            text += ": " + evidence;
        return TextWrap.Wrap(text, 92).Select(line => "    // " + line);
    }

    /// <summary>The members in C++. Padding rows are not written where the compiler inserts the same
    /// gap by itself; where it would not (a gap that alignment does not explain, or bytes after the
    /// last member), a hidden byte array keeps every later member at its offset.</summary>
    List<string> RenderFields(List<JsonNode> fields, int size, Dictionary<string, (int, int)> local)
    {
        var lines = new List<string>();
        int position = 0, widest = 1;
        void Gap(int until)
        {
            if (until <= position) return;
            lines.Add($"    [[bg3::hidden]] std::array<uint8_t, {until - position}> _Pad{position:X};");
            position = until;
        }
        foreach (var field in fields)
        {
            if (IsPadding(field)) continue;
            string type = Str(field, "type"), name = Str(field, "name");
            int offset = Int(field, "offset");
            var (fieldSize, align) = TypeSize(type, local);
            widest = Math.Max(widest, align);
            if (Up(position, align) < offset) Gap(offset);
            lines.AddRange(Comment(field));
            var array = CArray().Match(type);
            if (array.Success)
                lines.Add($"    std::array<{array.Groups[1].Value}, {array.Groups[2].Value}> {name};");
            else
            {
                // a raw pointer is kept in the layout but not shown to Lua: there is nothing to show
                string hidden = type.Contains("void*", StringComparison.Ordinal) ? "[[bg3::hidden]] " : "";
                // the name the field went by before it got a better one: kept as an alias
                string legacy = LayoutFile.Text(field["legacy"]) is { Length: > 0 } old && hidden.Length == 0 ? $"[[bg3::legacy({old})]] " : "";
                lines.Add($"    {hidden}{legacy}{type} {name};");
            }
            position = offset + fieldSize;
        }
        if (Up(position, widest) < size) Gap(size);
        return lines;
    }

    static IEnumerable<string> Remark(string text) => TextWrap.Wrap(text, 96).Select(line => "// " + line);

    /// <param name="knownStructs">Every nested struct the layout names, including those another
    /// layout of the namespace already declared: needed for sizes, not written again.</param>
    List<string> RenderComponent(JsonObject layout, List<JsonNode> structs, JsonNode? knownStructs)
    {
        var (engineNamespace, name) = NamespaceOf(Str(layout, "component"));
        string extName = Str(layout, "ext_name");
        bool oneFrame = LayoutFile.Truthy(layout["oneFrame"]);
        if (LayoutFile.Truthy(layout["tag"]))
            return [$"{(oneFrame ? "DEFINE_ONEFRAME_TAG_COMPONENT" : "DEFINE_TAG_COMPONENT")}({engineNamespace}, {name}, {extName})"];
        string macro = LayoutFile.Truthy(layout["proxy"]) ? "DEFINE_PROXY_COMPONENT" : oneFrame ? "DEFINE_ONEFRAME_COMPONENT" : "DEFINE_COMPONENT";
        var lines = new List<string>();
        var local = LocalTypes(layout, knownStructs);
        foreach (var nested in structs)
        {
            if (LayoutFile.Text(nested["summary"]) is { Length: > 0 } about) lines.AddRange(Remark(about));
            lines.Add($"struct {Str(nested, "name")}");
            lines.Add("{");
            lines.AddRange(RenderFields(List(nested, "fields"), Int(nested, "size"), local));
            lines.Add("};");
            lines.Add("");
        }
        if (LayoutFile.Text(layout["summary"]) is { Length: > 0 } summary) lines.AddRange(Remark(summary));
        if (LayoutFile.Text(layout["status"]) == "declared")
            lines.AddRange(Remark("NOT VERIFIED LIVE: this layout comes from the game's code; " + (LayoutFile.Text(layout["live_reason"]) ?? "")));
        lines.Add($"struct {name} : public BaseComponent");
        lines.Add("{");
        lines.Add($"    {macro}({extName}, \"{Str(layout, "component")}\")");
        lines.Add("");
        lines.AddRange(RenderFields(List(layout, "fields"), Int(layout, "size"), local));
        lines.Add("};");
        lines.Add("");
        return lines;
    }

