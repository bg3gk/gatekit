    /// <summary>Size of a struct Script Extender already declares, from the symbol database (its
    /// layouts are computed from the headers). The alignment is not stored: 8 unless the size rules it out.</summary>
    (int, int)? SeStructSize(string typeName)
    {
        if (Builtins.TryGetValue(typeName, out var builtin)) return builtin;
        if (symbols is null) return null;
        int cut = typeName.LastIndexOf("::", StringComparison.Ordinal);
        string space = cut < 0 ? "" : typeName[..cut], name = cut < 0 ? typeName : typeName[(cut + 2)..];
        if (space.StartsWith("bg3se::", StringComparison.Ordinal)) space = space[7..];   // the extender's own namespace, spelled out
        else if (space == "bg3se") space = "";
        var sizes = symbols.Query("SELECT namespace, size FROM se_types WHERE name = ? AND size IS NOT NULL AND kind = 'struct'", name)
            .Where(r => space.Length == 0 || ((r[0] as string) ?? "").EndsWith(space, StringComparison.Ordinal))
            .Select(r => Convert.ToInt32(r[1], CultureInfo.InvariantCulture)).Distinct().ToList();
        if (sizes.Count != 1) return null;   // unknown, or one name with different layouts: the layout must say which
        return (sizes[0], sizes[0] % 8 == 0 ? 8 : 4);
    }

    /// <summary>Size of an enumeration Script Extender declares, from its underlying type in the
    /// symbol database (<c>enums</c>): <c>DamageType</c> is a <c>uint8_t</c>. The same name in two
    /// namespaces with different underlying types is not sized - the layout must say which.</summary>
    (int, int)? SeEnumSize(string typeName)
    {
        if (symbols is null) return null;
        int cut = typeName.LastIndexOf("::", StringComparison.Ordinal);
        string space = cut < 0 ? "" : typeName[..cut], name = cut < 0 ? typeName : typeName[(cut + 2)..];
        if (space.StartsWith("bg3se::", StringComparison.Ordinal)) space = space[7..];
        else if (space == "bg3se") space = "";
        var sizes = symbols.Query("SELECT namespace, underlying FROM enums WHERE name = ?", name)
            .Where(r => space.Length == 0 || ((r[0] as string) ?? "") == space)
            .Select(r => Primitives.TryGetValue((r[1] as string) is "int" ? "int32_t" : (r[1] as string) ?? "", out var p) ? p : ((int, int)?)null)
            .Distinct().ToList();
        return sizes.Count == 1 ? sizes[0] : null;
    }

    /// <summary>'K, HashMap&lt;A, B&gt;' -> ['K', 'HashMap&lt;A, B&gt;']: template arguments at the top level.</summary>
    static List<string> SplitArguments(string text)
    {
        var parts = new List<string>();
        int depth = 0;
        var current = new StringBuilder();
        foreach (char c in text)
        {
            if (c == '<') depth++;
            if (c == '>') depth--;
            if (c == ',' && depth == 0)
            {
                parts.Add(current.ToString().Trim());
                current.Clear();
            }
            else current.Append(c);
        }
        parts.Add(current.ToString().Trim());
        return parts;
    }

    static int Up(int position, int align) => (position + align - 1) / align * align;

    /// <summary>(size, alignment) of a field type. <paramref name="local"/> holds the layout's own
    /// nested structs and the Script Extender types it names in "external_types".</summary>
    (int Size, int Align) TypeSize(string typeName, Dictionary<string, (int, int)> local)
    {
        if (Primitives.TryGetValue(typeName, out var known)) return known;
        if (Enums.TryGetValue(typeName, out known)) return known;
        if (local.TryGetValue(typeName, out known)) return known;
        if (SeStructSize(typeName) is { } declared) return declared;
        if (SeEnumSize(typeName) is { } enumeration) return enumeration;
        var template = Template().Match(typeName);
        if (template.Success)
        {
            string kind = template.Groups[1].Value;
            var arguments = SplitArguments(template.Groups[2].Value);
            if (kind == "std::optional" && arguments.Count == 1)
            {
                var (size, align) = TypeSize(arguments[0], local);   // the value, then a "has value" byte
                return (Up(size + 1, align), align);
            }
            if (kind == "std::array" && arguments.Count == 2 && int.TryParse(arguments[1], NumberStyles.None, CultureInfo.InvariantCulture, out int count))
            {
                var (size, align) = TypeSize(arguments[0], local);
                return (size * count, align);
            }
            foreach (var argument in arguments)   // the element types must be known too
                TypeSize(argument, local);
            switch (kind)
            {
                case "Array": return (16, 8);     // pointer, capacity, size
                case "HashSet": return (48, 8);   // hash buckets (pointer, count), next-index array, key array
                case "HashMap": return (64, 8);   // a HashSet of keys followed by an Array of values
            }
        }
        var array = CArray().Match(typeName);
        if (array.Success && Primitives.TryGetValue(array.Groups[1].Value, out var element))
            return (element.Size * int.Parse(array.Groups[2].Value, CultureInfo.InvariantCulture), element.Align);
        throw new LayoutError($"type '{typeName}' is not one whose size is known here");
    }

    /// <summary>Sizes of the types a layout brings along: the Script Extender types it names as
    /// "external_types": {name: [size, align]}, and its nested structs in order of declaration.</summary>
    Dictionary<string, (int, int)> LocalTypes(JsonObject layout, JsonNode? structs = null)
    {
        var local = new Dictionary<string, (int, int)>(StringComparer.Ordinal);
        if (layout["external_types"] is JsonObject external)
            foreach (var (name, stated) in external)
            {
                long? size = null, align = 8;
                switch (stated)
                {
                    case JsonArray pair:   // written as [size, alignment]
                        size = LayoutFile.Integer(pair.ElementAtOrDefault(0));
                        align = LayoutFile.Integer(pair.ElementAtOrDefault(1));
                        break;
                    case JsonObject o:
                        size = LayoutFile.Integer(o["size"]);
                        align = LayoutFile.Integer(o["align"]) ?? LayoutFile.Integer(o["alignment"]) ?? 8;
                        break;
                    case JsonValue v when v.TryGetValue<string>(out var text):
                        // a description such as "Script Extender SpellId (...), 0x38 bytes": the size is taken from it
                        var m = StatedSize().Match(text);
                        if (m.Success)
                            size = m.Groups[1].Success ? Convert.ToInt64(m.Groups[1].Value, 16) : long.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture);
                        break;
                    default:
                        size = LayoutFile.Integer(stated);
                        break;
                }
                if (size is null || align is null)
                    throw new LayoutError($"{Str(layout, "component")}: external type '{name}' needs [size, alignment], got {stated?.ToJsonString() ?? "null"}");
                local[name] = ((int)size, (int)align);
            }
        foreach (var nested in (structs ?? layout["structs"]) is JsonArray list ? list.Where(n => n is not null).Select(n => n!) : [])
        {
            int widest = 1;
            foreach (var field in List(nested, "fields"))
                widest = Math.Max(widest, TypeSize(Str(field, "type"), local).Align);
            local[Str(nested, "name")] = (Int(nested, "size"), widest);
        }
        return local;
    }

