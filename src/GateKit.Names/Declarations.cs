    static string ReadSource(string path) => File.ReadAllText(path, Encoding.UTF8);

    /// <summary>(top-level namespaces under bg3se, nested "a::b" ones) that Script Extender's own
    /// sources declare - every file of the tree except the generated header.</summary>
    (HashSet<string> Top, HashSet<string> Nested) SeNamespaces()
    {
        if (seNamespaces is { } known) return known;
        var top = new HashSet<string>(StringComparer.Ordinal);
        var nested = new HashSet<string>(StringComparer.Ordinal);
        string root = Path.Combine(tree, "BG3Extender");
        foreach (var pattern in new[] { "*.h", "*.inl", "*.cpp" })
            foreach (var path in Directory.EnumerateFiles(root, pattern, SearchOption.AllDirectories))
            {
                if (Path.GetFileName(path) == "Coverage.h") continue;
                string text = ReadSource(path);
                foreach (var name in BeginNs().Matches(text).Concat(NamespaceBg3se().Matches(text)).Select(m => m.Groups[1].Value))
                {
                    var parts = name.Split("::");
                    top.Add(parts[0]);
                    if (parts.Length >= 2) nested.Add(parts[0] + "::" + parts[1]);
                }
            }
        seNamespaces = (top, nested);
        return (top, nested);
    }

    [GeneratedRegex(@"DEFINE_(?:ONEFRAME_)?TAG_COMPONENT\(([\w:]+),")]
    private static partial Regex TagNamespace();

    /// <summary>Namespaces the committed header of the fork already declares structs in: they built
    /// and shipped as they are (moving their structs up could make two of the same name meet), so the
    /// general rule leaves them alone.</summary>
    HashSet<string> SettledNamespaces()
    {
        if (settled is not null) return settled;
        string shown = "";
        try
        {
            var start = new ProcessStartInfo("git") { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, StandardOutputEncoding = Encoding.UTF8 };
            foreach (var argument in new[] { "-C", tree, "show", "HEAD:BG3Extender/GameDefinitions/Components/Coverage.h" })
                start.ArgumentList.Add(argument);
            using var git = Process.Start(start);
            if (git is not null)
            {
                var errors = git.StandardError.ReadToEndAsync();
                shown = git.StandardOutput.ReadToEnd();
                git.WaitForExit();
                errors.Wait();
                if (git.ExitCode != 0) shown = "";
            }
        }
        catch (Exception e) when (e is System.ComponentModel.Win32Exception or InvalidOperationException or IOException)
        {
            shown = "";   // no git: nothing is known to be settled
        }
        settled = new HashSet<string>(BeginNs().Matches(shown).Concat(TagNamespace().Matches(shown)).Select(m => m.Groups[1].Value), StringComparer.Ordinal);
        return settled;
    }

    /// <summary>The C++ namespace under bg3se a type is declared in: the engine's own, as Script
    /// Extender does for most of its newer headers (BEGIN_NS(eoc::rest), BEGIN_NS(ecl::equipment)).</summary>
    string SeNamespace(string engineNamespace)
    {
        // A new namespace bg3se::a::b hides bg3se::b for every line of Script Extender that says
        // "b::Something" inside bg3se::a. So when b is one of Script Extender's top-level namespaces
        // and a::b is not a namespace it has itself, the struct is declared one level up, in bg3se::a.
        var parts = engineNamespace.Split("::");
        var (top, nested) = SeNamespaces();
        if (parts.Length >= 2 && top.Contains(parts[1]) && !nested.Contains(parts[0] + "::" + parts[1])
            && !SettledNamespaces().Contains(engineNamespace))
            return parts[0];
        foreach (var (hiding, instead) in HidingNamespaces)
            // also sub-namespaces: eoc::stats::proficiency would create bg3se::eoc::stats all the same
            if (engineNamespace == hiding || engineNamespace.StartsWith(hiding + "::", StringComparison.Ordinal))
                return instead;
        return engineNamespace;
    }

