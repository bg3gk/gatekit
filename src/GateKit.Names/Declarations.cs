    /// <summary>Engine class names Script Extender's own headers already declare (every header of
    /// the tree except ours): a layout for one of them is not generated - the author's wins.</summary>
    public HashSet<string> DeclaredUpstream()
    {
        var found = new HashSet<string>(StringComparer.Ordinal);
        foreach (var path in Directory.EnumerateFiles(Definitions, "*.h", SearchOption.AllDirectories))
        {
            if (Path.GetFileName(path) == "Coverage.h") continue;
            string text = ReadSource(path);
            foreach (Match m in DefineComponent().Matches(text)) found.Add(m.Groups[1].Value);
            foreach (Match m in DefineTag().Matches(text)) found.Add($"{m.Groups[1].Value}::{m.Groups[2].Value}");
            foreach (Match m in DefineBoost().Matches(text)) found.Add($"eoc::{m.Groups[1].Value}BoostComponent");
        }
        return found;
    }

    static string Shape(JsonNode nested) =>
        string.Join(";", List(nested, "fields").Select(f => $"{Str(f, "name")}@{Int(f, "offset")}:{Str(f, "type")}"));

    /// <summary>The same layouts, reordered only as far as needed: a layout that uses a nested
    /// struct declared by another layout of the namespace comes after the first one that declares it.</summary>
    static List<JsonObject> ProvidersFirst(List<JsonObject> members)
    {
        var declaredBy = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var layout in members)
            foreach (var nested in List(layout, "structs"))
                declaredBy.TryAdd(Str(nested, "name"), Str(layout, "component"));
        HashSet<string> Needs(JsonObject layout)
        {
            string component = Str(layout, "component");
            var own = List(layout, "structs").Select(n => Str(n, "name")).ToHashSet(StringComparer.Ordinal);
            string text = (layout["fields"]?.ToJsonString() ?? "") + string.Concat(List(layout, "structs").Select(n => n["fields"]?.ToJsonString() ?? ""));
            var needs = declaredBy.Keys.Where(name => !own.Contains(name) && declaredBy[name] != component
                                                      && Regex.IsMatch(text, $@"\b{Regex.Escape(name)}\b")).ToHashSet(StringComparer.Ordinal);
            needs.UnionWith(own.Where(name => declaredBy[name] != component));
            return needs;
        }
        var needed = members.ToDictionary(l => l, Needs);
        var ordered = new List<JsonObject>();
        var placed = new HashSet<string>(StringComparer.Ordinal);
        var waiting = members.ToList();
        while (waiting.Count > 0)
        {
            var ready = waiting.Where(l => needed[l].All(name => placed.Contains(declaredBy[name]))).ToList();
            if (ready.Count == 0) ready = [waiting[0]];   // a cycle: the original order, and the compiler says so
            foreach (var layout in ready)
            {
                ordered.Add(layout);
                placed.Add(Str(layout, "component"));
            }
            waiting = waiting.Where(l => !placed.Contains(Str(l, "component"))).ToList();
        }
        return ordered;
    }

    /// <summary>The header for these layouts, as text with line feeds.</summary>
    public string Render(IEnumerable<JsonObject> layouts)
    {
        var lines = new List<string>
        {
            "#pragma once", "",
            "// Component layouts added by the coverage project (research/coverage in GateKit).",
            "// GENERATED by `gatekit names generate` from research/coverage/layouts - edit the layout",
            "// files, not this header. A layout is here because it was checked against live instances",
            "// in the running game, or says on the struct that it was not; where a field's name comes",
            "// from is stated on the field.", "",
        };
        var groups = new SortedDictionary<string, List<JsonObject>>(StringComparer.Ordinal);
        foreach (var layout in layouts)
        {
            // "cpp_namespace" overrides where the struct is declared
            string space = layout["cpp_namespace"] is { } given ? LayoutFile.Text(given) ?? "" : SeNamespace(NamespaceOf(Str(layout, "component")).Namespace);
            if (!groups.TryGetValue(space, out var list)) groups[space] = list = [];
            list.Add(layout);
        }
        var sizes = new List<string>();
        foreach (var (space, group) in groups)
        {
            lines.Add(space.Length > 0 ? $"BEGIN_NS({space})" : "BEGIN_SE()");
            lines.Add("");
            var members = ProvidersFirst(group.OrderBy(l => LayoutFile.Truthy(l["tag"])).ThenBy(l => Str(l, "component"), StringComparer.Ordinal).ToList());
            var emitted = new Dictionary<string, string>(StringComparer.Ordinal);   // nested structs already written in this namespace
            foreach (var layout in members)
            {
                var all = List(layout, "structs");
                foreach (var nested in all)
                    if (emitted.TryGetValue(Str(nested, "name"), out var before) && before != Shape(nested))
                        throw new LayoutError($"{Str(layout, "component")}: nested struct {Str(nested, "name")} is declared differently by another layout of namespace {space}");
                var fresh = all.Where(n => !emitted.ContainsKey(Str(n, "name"))).ToList();   // declared once, by the first layout that needs it
                foreach (var nested in fresh) emitted[Str(nested, "name")] = Shape(nested);
                lines.AddRange(RenderComponent(layout, fresh, layout["structs"]));
                if (!LayoutFile.Truthy(layout["tag"]) && !LayoutFile.Truthy(layout["proxy"]))
                {
                    string prefix = space.Length > 0 ? $"bg3se::{space}::" : "bg3se::";
                    sizes.Add($"static_assert(sizeof({prefix}{NamespaceOf(Str(layout, "component")).Name}) == {Int(layout, "size")});");
                    foreach (var nested in fresh)
                        sizes.Add($"static_assert(sizeof({prefix}{Str(nested, "name")}) == {Int(nested, "size")});");
                }
            }
            if (lines[^1].Length > 0) lines.Add("");
            lines.Add(space.Length > 0 ? "END_NS()" : "END_SE()");
            lines.Add("");
        }
        lines.Add("// The sizes the game registers for these types.");
        lines.AddRange(sizes);
        lines.Add("");
        return string.Join("\n", lines);
    }

    /// <summary>Script Extender's name for a component must also be a member of ExtComponentType
    /// (GameDefinitions/Enumerations/ECS.inl); ours are kept in one marked block before E(Max).
    /// Returns the file's new text, with the carriage returns the file is kept with.</summary>
    public string RenderEnumeration(IEnumerable<JsonObject> layouts)
    {
        var lines = ReadSource(Enumerations).ReplaceLineEndings("\n").Split('\n').ToList();
        if (lines.Count > 0 && lines[^1].Length == 0) lines.RemoveAt(lines.Count - 1);
        int begin = lines.FindIndex(l => l.StartsWith(EnumBeginAny, StringComparison.Ordinal));
        if (begin >= 0)
        {
            int end = lines.IndexOf(EnumEnd, begin);
            if (end < 0) throw new LayoutError($"{Enumerations}: the coverage block begins and never ends");
            lines.RemoveRange(begin, Math.Min(end + 2, lines.Count) - begin);
        }
        int start = lines.IndexOf("BEGIN_ENUM(ExtComponentType, uint32_t)");
        int max = start < 0 ? -1 : lines.FindIndex(start, l => l.Trim() == "E(Max)");
        if (max < 0) throw new LayoutError($"{Enumerations}: no ExtComponentType enumeration ending in E(Max)");
        var block = new List<string> { EnumBegin };
        block.AddRange(layouts.Select(l => Str(l, "ext_name")).Order(StringComparer.Ordinal).Select(name => $"    E({name})"));
        block.Add(EnumEnd);
        block.Add("");
        lines.InsertRange(max, block);
        return string.Concat(lines.Select(l => l + "\r\n"));
    }

