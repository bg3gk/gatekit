"""Writes Script Extender's header for the layouts this project has confirmed.

    python research/coverage/generate.py            write GameDefinitions/Components/Coverage.h
    python research/coverage/generate.py --check    only validate the layout files

Input: every research/coverage/layouts/**/*.json whose "status" is "confirmed" (set by hand after
check.py's raw stage passed on live instances). A layout that is still a hypothesis never
reaches C++.

Every field carries a comment saying where its name comes from:
  toolkit   - the name is exported by Larian's Toolkit as an accessor of this class (a fact)
  game      - the member's own name in the game's symbols (macOS build, same version) (a fact)
  inferred  - named by us from how the game's code uses the field (the evidence follows)
  unknown   - the type is established, the meaning is not; the field is called field_<offset>
"""
import json
import os
import re
import sqlite3
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAYOUTS = HERE / "layouts"
# The Script Extender source tree the header is written into: the coverage worktree of the
# v34 base (branch coverage-v34), or another tree beside it named by COVERAGE_SE_TREE.
SE_TREE = HERE.parent / os.environ.get("COVERAGE_SE_TREE", "bg3se-v34-coverage")
DEFINITIONS = SE_TREE / "BG3Extender" / "GameDefinitions"
HEADER = DEFINITIONS / "Components" / "Coverage.h"
ENUMERATIONS = DEFINITIONS / "Enumerations" / "ECS.inl"
ENUM_BEGIN = "    // Coverage project (generated by research/coverage/generate.py)"
ENUM_END = "    // Coverage project: end"

# size and alignment of the field types a layout may use
PRIMITIVES = {
    "bool": (1, 1), "uint8_t": (1, 1), "int8_t": (1, 1), "uint16_t": (2, 2), "int16_t": (2, 2),
    "uint32_t": (4, 4), "int32_t": (4, 4), "float": (4, 4), "uint64_t": (8, 8), "int64_t": (8, 8),
    "EntityHandle": (8, 8), "FixedString": (4, 4), "Guid": (16, 8), "void*": (8, 8), "double": (8, 8), "int16_t": (2, 2), "int8_t": (1, 1),
    "UserId": (4, 4), "PlayerId": (2, 2), "double": (8, 8),
    "glm::vec2": (8, 4), "glm::vec3": (12, 4), "glm::vec4": (16, 4), "glm::quat": (16, 4),
}
# enumerations Script Extender already declares, by their size; Lua sees them as labels
ENUMS = {"stats::UnsheathState": (4, 4), "ItemSlot": (1, 1), "WeaponSetType": (1, 1)}
# Where a field's name comes from. "game": the game's own name of the member, read from the
# symbol table of the macOS build of the same version (ls::FieldMeta<Type Class::*, &Class::m_Name>,
# kept for replicated members) - a fact, like a Toolkit accessor.
SOURCES = {"toolkit": "Toolkit accessor", "game": "the game's own member name", "inferred": "inferred",
           "unknown": "unknown"}


class LayoutError(Exception):
    pass


# Script Extender's own types that are not in its headers' struct list
SE_BUILTINS = {"esv::inventory::MemberInteractionRequestData": (224, 8), "STDString": (24, 8), "Transform": (40, 4), "TranslatedString": (16, 4), "std::optional<glm::vec3>": (16, 4)}


def se_struct_size(type_name: str) -> tuple[int, int] | None:
    """Size of a struct Script Extender already declares, from the symbol base (its layouts are
    computed from the headers). The alignment is not stored: 8 unless the size rules it out."""
    if type_name in SE_BUILTINS:
        return SE_BUILTINS[type_name]
    sys.path.insert(0, str(HERE.parent))
    import oldrepo
    base = oldrepo.symbols_db()
    if not base.exists():
        return None
    namespace, _, name = type_name.rpartition("::")
    with sqlite3.connect(base) as symbols:
        rows = symbols.execute("SELECT namespace, size FROM se_types WHERE name = ? AND size IS NOT NULL "
                               "AND kind = 'struct'", (name,)).fetchall()
    rows = [row for row in rows if not namespace or (row[0] or "").endswith(namespace)]
    sizes = {row[1] for row in rows}
    if len(sizes) != 1:
        return None  # unknown, or the same name with different layouts: the layout must say which
    size = sizes.pop()
    return size, 8 if size % 8 == 0 else 4


def split_arguments(text: str) -> list[str]:
    """'K, HashMap<A, B>' -> ['K', 'HashMap<A, B>']: template arguments at the top level."""
    parts, depth, current = [], 0, ""
    for char in text:
        depth += char == "<"
        depth -= char == ">"
        if char == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += char
    return parts + [current.strip()]


def type_size(type_name: str, local: dict | None = None) -> tuple[int, int]:
    """(size, alignment) of a field type. `local` holds the layout's own nested structs and the
    Script Extender types it names in "external_types"."""
    local = local or {}
    if type_name in PRIMITIVES:
        return PRIMITIVES[type_name]
    if type_name in ENUMS:
        return ENUMS[type_name]
    if type_name in local:
        return local[type_name]
    known = se_struct_size(type_name)
    if known:
        return known
    template = re.fullmatch(r"([\w:]+)<(.+)>", type_name)
    if template:
        kind, arguments = template.group(1), split_arguments(template.group(2))
        if kind == "std::optional" and len(arguments) == 1:
            size, align = type_size(arguments[0], local)  # the value, then a "has value" byte
            return -(-(size + 1) // align) * align, align
        if kind == "std::array" and len(arguments) == 2:
            size, align = type_size(arguments[0], local)
            return size * int(arguments[1]), align
        for argument in arguments:  # the element types must be known too
            type_size(argument, local)
        if kind == "Array":
            return 16, 8  # pointer, capacity, size
        if kind == "HashSet":
            return 48, 8  # hash buckets (pointer, count), next-index array, key array
        if kind == "HashMap":
            return 64, 8  # a HashSet of keys followed by an Array of values
    array = re.fullmatch(r"(\w+)\[(\d+)\]", type_name)
    if array and array.group(1) in PRIMITIVES:
        size, align = PRIMITIVES[array.group(1)]
        return size * int(array.group(2)), align
    raise LayoutError(f"type {type_name!r} is not one generate.py knows the size of")


# Statuses that put a layout into the header. "confirmed": the raw check passed on live
# instances holding data. "declared": established from the game's code, the size agrees with
# the registry, but no live instance was read - the header, the index and the report all say
# "not verified live" for it (the layout carries "live": "not verified" and "live_reason").
IN_BUILD = ("confirmed", "declared")


def load(only_confirmed: bool = True) -> list[dict]:
    layouts = []
    for path in sorted(LAYOUTS.rglob("*.json")):
        layout = json.loads(path.read_text(encoding="utf-8"))
        layout["_path"] = path
        if layout.get("kind") == "system":
            continue  # systems are objects with behaviour; they are not generated yet
        if only_confirmed and (layout.get("status") not in IN_BUILD or layout.get("hold")):
            continue  # "hold": a reason the layout cannot be generated yet, whatever its status
        layouts.append(layout)
    return layouts


def is_padding(field: dict) -> bool:
    return field["name"].startswith("_Pad")


def local_types(layout: dict) -> dict:
    """Sizes of the types a layout brings along: its nested structs (in order of declaration)
    and the existing Script Extender types it names as "external_types": {name: [size, align]}."""
    local = {}
    for name, size in (layout.get("external_types") or {}).items():
        # written as [size, alignment]; a bare size or {"size", "align"} is accepted too
        if isinstance(size, dict):
            size = [size.get("size"), size.get("align") or size.get("alignment") or 8]
        elif isinstance(size, str):
            # a description such as "Script Extender SpellId (...), 0x38 bytes": take the size from it
            stated = re.search(r"0x([0-9A-Fa-f]+)\s*bytes|(\d+)\s*bytes", size)
            size = [int(stated.group(1), 16) if stated and stated.group(1) else
                    int(stated.group(2)) if stated else None, 8]
        elif not isinstance(size, (list, tuple)):
            size = [size, 8]
        try:
            local[name] = (int(size[0]), int(size[1]))
        except (TypeError, ValueError, IndexError):
            raise LayoutError(f"{layout['component']}: external type {name!r} needs [size, alignment], got {size!r}")
    for struct in layout.get("structs") or []:
        widest = max((type_size(f["type"], local)[1] for f in struct["fields"]), default=1)
        local[struct["name"]] = (struct["size"], widest)
    return local


def validate_fields(owner: str, fields: list[dict], size: int, local: dict) -> None:
    position, widest = 0, 1
    for field in fields:
        field_size, align = type_size(field["type"], local)
        widest = max(widest, align)
        if field["offset"] < position:
            raise LayoutError(f"{owner}.{field['name']}: overlaps the field before it")
        if field["offset"] % align:
            raise LayoutError(f"{owner}.{field['name']}: offset {field['offset']} is not aligned to {align}")
        natural = -(-position // align) * align
        if not is_padding(field) and field["offset"] != natural:
            raise LayoutError(f"{owner}.{field['name']}: C++ would place it at {natural}, the layout says "
                              f"{field['offset']}; add the unknown field in between")
        if field.get("source") not in SOURCES and not is_padding(field):
            raise LayoutError(f"{owner}.{field['name']}: source must be one of {sorted(SOURCES)}")
        if field.get("source") == "inferred" and not field.get("evidence"):
            raise LayoutError(f"{owner}.{field['name']}: an inferred name needs its evidence")
        position = field["offset"] + field_size
    total = -(-position // widest) * widest
    if total != size:
        raise LayoutError(f"{owner}: fields end at {position} (struct size {total}), expected {size}")


def validate(layout: dict) -> None:
    """Fields in order, no overlap, alignment respected, the size covered exactly - for the
    component and for every nested struct."""
    name = layout["component"]
    if layout.get("tag"):
        if layout.get("fields"):
            raise LayoutError(f"{name}: a tag has no fields")
        return
    local = local_types(layout)
    for struct in layout.get("structs") or []:
        validate_fields(f"{name}/{struct['name']}", struct["fields"], struct["size"], local)
    validate_fields(name, layout["fields"], layout["size"], local)


def namespace_of(component: str) -> tuple[str, str]:
    """('ecl::unsheath', 'VisualStateComponent'); Script Extender keeps eoc types at its root."""
    parts = component.split("::")
    return "::".join(parts[:-1]), parts[-1]


# C++ namespaces that must not be created under bg3se: bg3se::ecl::level would hide bg3se::level
# for the unqualified uses inside bg3se::ecl (found by building). Types of such a namespace are
# declared one level up.
HIDING_NAMESPACES = {
    "ecl::level": "ecl", "esv::level": "esv",  # bg3se::level: LuaSharedLibs.cpp
    "ecl::ui": "ecl",                          # bg3se::ui: ScriptExtenderClient.h
    "eoc::stats": "eoc",                       # bg3se::stats: Components/Roll.h
    "eoc::character_creation": "eoc",          # bg3se::character_creation: used unqualified inside bg3se::eoc
}


_SE_NAMESPACES = None


def se_namespaces() -> tuple[set[str], set[str]]:
    """(top-level namespaces under bg3se, nested "a::b" ones) that Script Extender's own sources
    declare - every file of the tree except our generated header."""
    global _SE_NAMESPACES
    if _SE_NAMESPACES is None:
        top, nested = set(), set()
        root = DEFINITIONS.parent  # BG3Extender
        for path in list(root.rglob("*.h")) + list(root.rglob("*.inl")) + list(root.rglob("*.cpp")):
            if path.name == HEADER.name:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            for name in re.findall(r"BEGIN_NS\(([\w:]+)\)", text) + re.findall(r"namespace bg3se::([\w:]+)", text):
                parts = name.split("::")
                top.add(parts[0])
                if len(parts) >= 2:
                    nested.add("::".join(parts[:2]))
        _SE_NAMESPACES = (top, nested)
    return _SE_NAMESPACES


_SETTLED = None


def settled_namespaces() -> set[str]:
    """Namespaces the committed header of the fork branch already declares structs in: they
    built and shipped as they are (moving their structs up could make two of the same name
    meet), so the general rule leaves them alone."""
    global _SETTLED
    if _SETTLED is None:
        import subprocess
        shown = subprocess.run(["git", "-C", str(SE_TREE), "show", "HEAD:BG3Extender/GameDefinitions/Components/Coverage.h"],
                               capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
        _SETTLED = set(re.findall(r"BEGIN_NS\(([\w:]+)\)", shown))
        _SETTLED |= set(re.findall(r"DEFINE_(?:ONEFRAME_)?TAG_COMPONENT\(([\w:]+),", shown))
    return _SETTLED


def se_namespace(engine_namespace: str) -> str:
    """The C++ namespace under bg3se a type is declared in: the engine's own, as Script Extender
    does for most of its newer headers (BEGIN_NS(eoc::rest), BEGIN_NS(ecl::equipment))."""
    # The general case of the table above: a new namespace bg3se::a::b hides bg3se::b for every
    # line of Script Extender that says "b::Something" inside bg3se::a. So when b is one of
    # Script Extender's top-level namespaces and a::b is not a namespace it has itself, the
    # struct is declared one level up, in bg3se::a.
    parts = engine_namespace.split("::")
    top, nested = se_namespaces()
    if len(parts) >= 2 and parts[1] in top and "::".join(parts[:2]) not in nested \
            and engine_namespace not in settled_namespaces():
        return parts[0]
    for hiding, instead in HIDING_NAMESPACES.items():
        # also sub-namespaces: eoc::stats::proficiency would create bg3se::eoc::stats all the same
        if engine_namespace == hiding or engine_namespace.startswith(hiding + "::"):
            return instead
    return engine_namespace


def comment(field: dict) -> list[str]:
    text = SOURCES[field["source"]]
    if field.get("evidence"):
        text += ": " + field["evidence"]
    return ["    // " + line for line in textwrap.wrap(text, 92)]


def render_fields(fields: list[dict], size: int, local: dict) -> list[str]:
    """The members in C++. Padding rows are not written where the compiler inserts the same gap
    by itself; where it would not (a gap that alignment does not explain, or bytes after the
    last member), a hidden byte array keeps every later member at its offset."""
    lines, position, widest = [], 0, 1

    def gap(until: int) -> None:
        nonlocal position
        if until > position:
            lines.append(f"    [[bg3::hidden]] std::array<uint8_t, {until - position}> _Pad{position:X};")
            position = until

    for field in fields:
        if is_padding(field):
            continue
        field_size, align = type_size(field["type"], local)
        widest = max(widest, align)
        if -(-position // align) * align < field["offset"]:
            gap(field["offset"])
        lines += comment(field)
        array = re.fullmatch(r"(\w+)\[(\d+)\]", field["type"])
        if array:
            lines.append(f"    std::array<{array.group(1)}, {array.group(2)}> {field['name']};")
        else:
            # a raw pointer is kept in the layout but not shown to Lua: there is nothing to show
            hidden = "[[bg3::hidden]] " if "void*" in field["type"] else ""
            # the name the field shipped under before it got the game's own: kept as an alias
            legacy = f"[[bg3::legacy({field['legacy']})]] " if field.get("legacy") and not hidden else ""
            lines.append(f"    {hidden}{legacy}{field['type']} {field['name']};")
        position = field["offset"] + field_size
    if -(-position // widest) * widest < size:
        gap(size)
    return lines


def render_component(layout: dict) -> list[str]:
    engine_namespace, struct = namespace_of(layout["component"])
    if layout.get("tag"):
        macro = "DEFINE_ONEFRAME_TAG_COMPONENT" if layout.get("oneFrame") else "DEFINE_TAG_COMPONENT"
        return [f"{macro}({engine_namespace}, {struct}, {layout['ext_name']})"]
    macro = "DEFINE_ONEFRAME_COMPONENT" if layout.get("oneFrame") else "DEFINE_COMPONENT"
    if layout.get("proxy"):
        macro = "DEFINE_PROXY_COMPONENT"
    lines = []
    # sizes of nested structs, including those another layout of the namespace already declared
    local = local_types(dict(layout, structs=layout.get("_known_structs") or layout.get("structs")))
    for nested in layout.get("structs") or []:
        if nested.get("summary"):
            lines += ["// " + line for line in textwrap.wrap(nested["summary"], 96)]
        lines += [f"struct {nested['name']}", "{",
                  *render_fields(nested["fields"], nested["size"], local), "};", ""]
    if layout.get("summary"):
        lines += ["// " + line for line in textwrap.wrap(layout["summary"], 96)]
    if layout.get("status") == "declared":
        lines += ["// " + line for line in textwrap.wrap(
            "NOT VERIFIED LIVE: this layout comes from the game's code; " + layout.get("live_reason", ""), 96)]
    lines += [f"struct {struct} : public BaseComponent", "{",
              f"    {macro}({layout['ext_name']}, \"{layout['component']}\")", "",
              *render_fields(layout["fields"], layout["size"], local), "};", ""]
    return lines


def declared_upstream() -> set[str]:
    """Engine class names Script Extender's own headers already declare (every header of the
    tree except ours): a layout for one of them is not generated - the author's wins."""
    found = set()
    for path in DEFINITIONS.rglob("*.h"):
        if path.name == HEADER.name:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        found.update(re.findall(r'DEFINE_(?:PROXY_|ONEFRAME_)?COMPONENT\(\w+,\s*"([\w:]+)"\)', text))
        for namespace, name in re.findall(r"DEFINE_(?:ONEFRAME_)?TAG_COMPONENT\(([\w:]+),\s*(\w+),", text):
            found.add(f"{namespace}::{name}")
        for name in re.findall(r'DEFN_BOOST\(\s*(\w+),', text):
            found.add(f"eoc::{name}BoostComponent")
    return found


def providers_first(members: list[dict]) -> list[dict]:
    """The same layouts, reordered only as far as needed: a layout that uses a nested struct
    declared by another layout of the namespace comes after the first one that declares it."""
    declared_by = {}
    for layout in members:
        for nested in layout.get("structs") or []:
            declared_by.setdefault(nested["name"], layout["component"])

    def needs(layout: dict) -> set[str]:
        own = {nested["name"] for nested in layout.get("structs") or []}
        text = json.dumps([layout.get("fields"), [n["fields"] for n in layout.get("structs") or []]])
        return {name for name in declared_by if name not in own and re.search(rf"\b{re.escape(name)}\b", text)
                and declared_by[name] != layout["component"]} | \
               {name for name in own if declared_by[name] != layout["component"]}

    ordered, placed, waiting = [], set(), list(members)
    while waiting:
        ready = [l for l in waiting if all(declared_by[name] in placed for name in needs(l))]
        if not ready:
            ready = waiting[:1]  # a cycle: keep the original order and let the compiler say so
        for layout in ready:
            ordered.append(layout)
            placed.add(layout["component"])
        waiting = [l for l in waiting if l["component"] not in placed]
    return ordered


def shape(nested: dict) -> str:
    """What makes two declarations of a nested struct the same: members, offsets, types (the
    comments may differ between the layouts that share it)."""
    return json.dumps([(f["name"], f["offset"], f["type"]) for f in nested["fields"]])


def render(layouts: list[dict]) -> str:
    out = ["#pragma once", "",
           "// Component layouts added by the coverage project (se-fork/coverage in the GateKit).",
           "// GENERATED by research/coverage/generate.py from research/coverage/layouts - edit the",
           "// layout files, not this header. Each layout was checked against live instances in the",
           "// running game before it was allowed here; where a field's name comes from is stated",
           "// on the field.", ""]
    groups: dict[str, list[dict]] = {}
    for layout in layouts:
        # "cpp_namespace" overrides where the struct is declared: a new C++ namespace can hide one
        # Script Extender's own code uses unqualified (ecl::level hid bg3se::level in LuaSharedLibs.cpp)
        namespace = layout.get("cpp_namespace", se_namespace(namespace_of(layout["component"])[0]))
        groups.setdefault(namespace, []).append(layout)
    sizes = []
    for namespace in sorted(groups):
        out += [f"BEGIN_NS({namespace})" if namespace else "BEGIN_SE()", ""]
        members = providers_first(sorted(groups[namespace], key=lambda l: (bool(l.get("tag")), l["component"])))
        emitted: dict[str, str] = {}  # nested structs already written in this namespace
        for layout in members:
            for nested in layout.get("structs") or []:
                body = shape(nested)
                if nested["name"] in emitted and emitted[nested["name"]] != body:
                    raise LayoutError(f"{layout['component']}: nested struct {nested['name']} is declared "
                                      f"differently by another layout of namespace {namespace}")
            shared = [n for n in layout.get("structs") or [] if n["name"] in emitted]
            if shared:  # declared once, by the first layout that needs it
                layout = dict(layout, _known_structs=layout["structs"],
                              structs=[n for n in layout["structs"] if n["name"] not in emitted])
            for nested in layout.get("structs") or []:
                emitted[nested["name"]] = shape(nested)
            out += render_component(layout)
            if not layout.get("tag") and not layout.get("proxy"):
                struct = namespace_of(layout["component"])[1]
                qualified = f"bg3se::{namespace}::{struct}" if namespace else f"bg3se::{struct}"
                sizes.append(f"static_assert(sizeof({qualified}) == {layout['size']});")
                for nested in layout.get("structs") or []:
                    prefix = f"bg3se::{namespace}::" if namespace else "bg3se::"
                    sizes.append(f"static_assert(sizeof({prefix}{nested['name']}) == {nested['size']});")
        if out[-1] != "":
            out.append("")
        out += ["END_NS()" if namespace else "END_SE()", ""]
    out += ["// The sizes the game registers for these types.", *sizes, ""]
    return "\n".join(out)


def write_enumeration(layouts: list[dict]) -> None:
    """Script Extender's name for a component must also be a member of ExtComponentType
    (GameDefinitions/Enumerations/ECS.inl); ours are kept in one marked block before E(Max)."""
    lines = ENUMERATIONS.read_text(encoding="utf-8").splitlines()  # the file has CRLF endings
    if ENUM_BEGIN in lines:
        del lines[lines.index(ENUM_BEGIN):lines.index(ENUM_END) + 2]
    start = lines.index("BEGIN_ENUM(ExtComponentType, uint32_t)")
    end = next(i for i in range(start, len(lines)) if lines[i].strip() == "E(Max)")
    block = [ENUM_BEGIN, *(f"    E({name})" for name in sorted(l["ext_name"] for l in layouts)), ENUM_END, ""]
    lines[end:end] = block
    ENUMERATIONS.write_text("".join(line + "\r\n" for line in lines), encoding="utf-8", newline="")


def main() -> int:
    everything = load(only_confirmed=False)
    problems = 0
    for layout in everything:
        try:
            validate(layout)
        except Exception as problem:
            # an unfinished hypothesis may be invalid; a confirmed layout may not
            problems += layout.get("status") in IN_BUILD
            print(f"INVALID {layout['_path'].name}: {problem}")
    confirmed = [l for l in everything if l.get("status") in IN_BUILD and not l.get("hold")]
    upstream = declared_upstream()
    theirs = sorted(l["component"] for l in confirmed if l["component"] in upstream)
    if theirs:
        print(f"{len(theirs)} confirmed layouts are left out: Script Extender declares the type itself now")
        (HERE / "work").mkdir(exist_ok=True)
        (HERE / "work" / "declared-upstream.json").write_text(json.dumps(theirs, indent=1), encoding="utf-8")
    confirmed = [l for l in confirmed if l["component"] not in upstream]
    print(f"{len(everything)} layouts, {len(confirmed)} confirmed, {problems} confirmed ones invalid")
    if problems or "--check" in sys.argv:
        return 1 if problems else 0
    HEADER.write_text(render(confirmed), encoding="utf-8", newline="\n")
    write_enumeration(confirmed)
    print(f"wrote {HEADER} and the names into {ENUMERATIONS.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
